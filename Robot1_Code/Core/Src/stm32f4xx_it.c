/**
  * @brief This function handles EXTI line[9:5] interrupts.
  */
void EXTI9_5_IRQHandler(void)
{
  /* USER CODE BEGIN EXTI9_5_IRQn 0 */
	if(__HAL_GPIO_EXTI_GET_FLAG(En1_Ext_Pin)){
		if(encodera) counter[0]--;
		else if(!encodera) counter[0]++;
		__HAL_GPIO_EXTI_CLEAR_IT(En1_Ext_Pin);
	}
	if(__HAL_GPIO_EXTI_GET_FLAG(En2_Ext_Pin)){
		if(encoderb) counter[1]--;
		else if(!encoderb) counter[1]++;
		__HAL_GPIO_EXTI_CLEAR_IT(En2_Ext_Pin);
	}
	if(__HAL_GPIO_EXTI_GET_FLAG(En3_Ext_Pin)){
		if(encoderc) counter[2]--;
		else if(!encoderc) counter[2]++;
		__HAL_GPIO_EXTI_CLEAR_IT(En3_Ext_Pin);
		}
	if(__HAL_GPIO_EXTI_GET_FLAG(En4_Ext_Pin)){
		if(encoderd) counter[3]--;
		else if(!encoderd) counter[3]++;
		__HAL_GPIO_EXTI_CLEAR_IT(En4_Ext_Pin);
	}
  /* USER CODE END EXTI9_5_IRQn 0 */
  HAL_GPIO_EXTI_IRQHandler(En4_Ext_Pin);
  HAL_GPIO_EXTI_IRQHandler(En2_Ext_Pin);
  HAL_GPIO_EXTI_IRQHandler(En3_Ext_Pin);
  HAL_GPIO_EXTI_IRQHandler(En1_Ext_Pin);
  /* USER CODE BEGIN EXTI9_5_IRQn 1 */

  /* USER CODE END EXTI9_5_IRQn 1 */
}

